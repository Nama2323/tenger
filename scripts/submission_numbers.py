"""docs/SUBMISSION-NUMBERS.md: every number the project page or video might quote, read from its source file.

    python -m scripts.submission_numbers

Each line is written from the data files at run time (nothing typed by hand), with its file and field.
"""
import json
import math
from pathlib import Path

from astropy.time import Time

ROOT = Path(__file__).resolve().parent.parent
DATA = ROOT / "static" / "data"
OUT = ROOT / "docs" / "SUBMISSION-NUMBERS.md"


def load(relative: str) -> dict:
    return json.loads((DATA / relative).read_text())


def date(mjd: float) -> str:
    return Time(mjd, format="mjd").to_value("iso", subfmt="date")


def measurement(investigation: dict, ident: str) -> dict:
    return next(m for m in investigation["measurements"] if m.get("id") == ident)


def axes(cov) -> tuple[float, float]:
    import numpy as np
    values = np.linalg.eigvalsh(np.array(cov, float))
    k = 2.4477468306808166
    return k * math.sqrt(values[1]), k * math.sqrt(values[0])


def build() -> str:
    lines = ["# Numbers for the project page and the video", "",
             "Generated by `python -m scripts.submission_numbers` from the data files (nothing typed by hand).",
             "Each line: the plain-English statement, then the source file under `static/data/` and its field.", ""]

    def add(text: str, source: str, field: str) -> None:
        lines.append(f"- {text} — `{source}` → `{field}`")

    lines += ["## Stars (retrospective, catalogue-assisted)", ""]
    for key, name, trial in (("barnard", "Barnard's Star", "barnard-position-2026b"),
                             ("epsindib", "Epsilon Indi B", "epsindib-position-2026b")):
        investigation = load(f"{key}/investigation.json")
        measured, catalogue = measurement(investigation, "m-pm-total"), measurement(investigation, "m-pm-total-catalogue")
        add(f"{name}: our SPHEREx proper motion is {measured['value']:.3f} ± {measured['sigma']:.3f}″/yr; "
            f"the catalogue gives {catalogue['value']:.3f}″/yr.", f"{key}/investigation.json",
            "measurements[id=m-pm-total].value, .sigma; measurements[id=m-pm-total-catalogue].value")
        verification = load(f"trials/{trial}/verification.json")
        model, base = verification["residuals"]["model"], verification["residuals"]["baseline"]
        add(f"{name}: position forecast for the held-out visit: {verification['status']}, {model['error_arcsec']:.2f}″ off "
            f"(D² {model['d2']:.2f}, 95% limit 5.99). Retrospective: that visit had been seen.",
            f"trials/{trial}/verification.json", "status, residuals.model.error_arcsec, residuals.model.d2")
        add(f"{name}: the straight-line baseline missed by {base['error_arcsec']:.2f}″ (D² {base['d2']:.1f}).",
            f"trials/{trial}/verification.json", "residuals.baseline.error_arcsec, .d2")

    lines += ["", "## Pluto", ""]
    verification = load("trials/pluto-position-2026b/verification.json")
    model = verification["residuals"]["model"]
    trial = load("trials/pluto-position-2026b/trial.json")
    add(f"Pluto, prospective forecast for {date(verification['t_mjd'])}: {verification['status']}, {model['error_arcsec']:.2f}″ off "
        f"(D² {model['d2']:.2f} against 5.99).", "trials/pluto-position-2026b/verification.json",
        "status, t_mjd, residuals.model.error_arcsec, residuals.model.d2")
    add(f"Pluto's prospective label is pending: confirmation_pending = {str(trial.get('confirmation_pending')).lower()} "
        "(the other teammates' statement has not been given).", "trials/pluto-position-2026b/trial.json", "confirmation_pending")
    postmortem = load("trials/pluto/postmortem.json")
    ident = postmortem["identification"]
    add(f"We did find Pluto: our position is {ident['observed_minus_horizons_total_arcsec']:.2f}″ from JPL Horizons; "
        f"the frozen forecast was {ident['frozen_model_minus_horizons_total_arcsec']:.2f}″ off.", "trials/pluto/postmortem.json",
        "identification.observed_minus_horizons_total_arcsec, .frozen_model_minus_horizons_total_arcsec")
    sensitivity = postmortem["uncertainty_test"]["sensitivity"]
    for level in ("0.1", "0.2", "0.4"):
        add(f"Post-mortem (exploratory): with {level}″ shared error per visit × detector group, the miss would have had "
            f"D² {sensitivity[level]['d2_with_inflated_covariance']:.2f} ({sensitivity[level]['would_have_been']}).",
            "trials/pluto/postmortem.json", f"uncertainty_test.sensitivity[\"{level}\"].d2_with_inflated_covariance")
    jack = postmortem["uncertainty_test"]["jackknife_by_visit_and_array"]
    add(f"Post-mortem: a leave-one-group-out region of {jack['ellipse_95']['semi_major_95_arcsec']:.1f}″ × "
        f"{jack['ellipse_95']['semi_minor_95_arcsec']:.1f}″ would have held the miss (D² {jack['d2_with_jackknife_covariance']:.2f}).",
        "trials/pluto/postmortem.json", "uncertainty_test.jackknife_by_visit_and_array")
    hindcast = load("trials/pluto/hindcast-v2.json")["new_method"]
    add(f"Hindcast (exploratory): method v2 on the same training data would have been {hindcast['error_arcsec']:.2f}″ off "
        f"inside a {hindcast['along_track_95_arcsec']:.1f}″ × {hindcast['cross_track_95_arcsec']:.1f}″ region (D² {hindcast['d2']:.2f}).",
        "trials/pluto/hindcast-v2.json", "new_method.error_arcsec, .along_track_95_arcsec, .cross_track_95_arcsec, .d2")

    lines += ["", "## Open forecasts (never counted until IRSA releases the data)", ""]
    v1 = load("trials/pluto-position-open-2027a/prediction.json")
    major, minor = axes(v1["model"]["cov_arcsec2"])
    add(f"Pluto v1, {date(v1['t_mjd'])}: RA {v1['model']['ra_deg']:.5f}°, Dec {v1['model']['dec_deg']:.5f}°, "
        f"95% ellipse {major:.1f}″ × {minor:.2f}″.", "trials/pluto-position-open-2027a/prediction.json", "t_mjd, model.ra_deg, .dec_deg, .cov_arcsec2")
    for trial_id in ("pluto-position-open-2027a-v2b", "pluto-position-open-2027b-v2b"):
        prediction = load(f"trials/{trial_id}/prediction.json")
        model = prediction["model"]
        add(f"Pluto v2 (made after the 2026 miss), {date(prediction['t_mjd'])}: RA {model['ra_deg']:.5f}°, Dec {model['dec_deg']:.5f}°, "
            f"95% region {model['along_track_95_arcsec']:.1f}″ along × {model['cross_track_95_arcsec']:.1f}″ across the track.",
            f"trials/{trial_id}/prediction.json", "t_mjd, model.ra_deg, .dec_deg, .along_track_95_arcsec, .cross_track_95_arcsec")
    makemake = load("trials/makemake-position-open-2027a/prediction.json")
    add(f"Makemake open forecast: {makemake['prediction_status']}.", "trials/makemake-position-open-2027a/prediction.json", "prediction_status")

    lines += ["", "## Scoreboard", ""]
    board = load("scoreboard.json")
    for category, counts in board["counts"].items():
        text = ", ".join(f"{count} {status.replace('_', ' ')}" for status, count in counts.items() if count)
        add(f"{category.replace('_', ' ')}: {text}.", "scoreboard.json", f"counts.{category}")

    lines += ["", "## Could SPHEREx see Planet X? (artificial injections, measured depth)", ""]
    depth = load("planetx/depth.json")
    total = sum(p["injected"] for band in depth["bands"] for p in band["pooled"]["curve"])
    blanks = sum(band["pooled"]["false_detection"]["blanks"] for band in depth["bands"])
    false = sum(band["pooled"]["false_detection"]["false"] for band in depth["bands"])
    exposures = len({e["obs_key"] for band in depth["bands"] for f in band["fields"] for e in f["exposures"]})
    add(f"{total:,} artificial sources injected into {exposures} real exposures; {false} false detections in {blanks:,} blank tests.",
        "planetx/depth.json", "bands[].pooled.curve[].injected; bands[].pooled.false_detection; bands[].fields[].exposures")
    for band in depth["bands"]:
        d50, d90 = band["pooled"]["depth_50_ab"], band["pooled"]["depth_90_ab"]
        add(f"One exposure near {band['nominal_um']} µm ({band['published_band']}) finds half of the sources at AB {d50['value']:.2f} "
            f"({d50['interval'][0]:.2f}–{d50['interval'][1]:.2f}) and 90% at AB {d90['value']:.2f}.", "planetx/depth.json",
            f"bands[id={band['id']}].pooled.depth_50_ab, .depth_90_ab")
    for verdict in depth["verdicts"]:
        if verdict["model_id"].startswith("lm16-700au-") or verdict["model_id"] == "wise-limit" or verdict["model_id"] == "lm16-280au-i":
            found = verdict["recovered_fraction"]
            share = f"; one exposure finds {found['value'] * 100:.0f}% of sources that faint" if found.get("value") else ""
            add(f"{verdict['model_id']}: predicted AB {verdict['model_mag_ab']:.2f} vs our {verdict['depth_50_ab']:.2f}: "
                f"{verdict['gap_mag']['value']:.2f} mag fainter (×{verdict['factor_in_flux']:.1f} in flux){share}.",
                "planetx/depth.json", f"verdicts[model_id={verdict['model_id']}].gap_mag, .recovered_fraction")

    lines += ["", "## Asteroid batch (blind forecasts)", ""]
    batch = load("batches/asteroids-2026a.json")
    calibration = batch["calibration"]
    add(f"{len(batch['rows'])} asteroids frozen in git (commit {batch['receipt']['commit_sha'][:7]}, {batch['receipt']['frozen_utc']}) "
        "before any evaluation image was opened.", "batches/asteroids-2026a.json", "rows, receipt.commit_sha, receipt.frozen_utc")
    add(f"Calibration: {calibration['k_inside']} of {calibration['n']} scored forecasts inside the 95% region "
        f"(95% interval for the true coverage {calibration['interval'][0]:.3f}–{calibration['interval'][1]:.2f}, Clopper–Pearson).",
        "batches/asteroids-2026a.json", "calibration")
    statuses = {}
    for row in batch["rows"]:
        statuses[row["status"]] = statuses.get(row["status"], 0) + 1
    add("Outcomes: " + ", ".join(f"{count} {status.replace('_', ' ')}" for status, count in sorted(statuses.items())) + ".",
        "batches/asteroids-2026a.json", "rows[].status")
    hit = next((row for row in batch["rows"] if row["status"] == "hit"), None)
    if hit:
        add(f"The scored forecast ({hit['name'].split('(')[0].strip()}) was {hit['model_error_arcsec']:.1f}″ off (D² {hit['model_d2']:.2f}); "
            f"the straight line was {hit['baseline_error_arcsec'] / 3600:.1f}° off.", "batches/asteroids-2026a.json",
            "rows[status=hit].model_error_arcsec, .model_d2, .baseline_error_arcsec")
    coverage = batch["exploratory_horizons_coverage"]["primary"]
    add(f"After the verdicts (exploratory, not counted): JPL's position lay inside the frozen 95% region for "
        f"{coverage['k_inside']} of {coverage['n']} objects.", "batches/asteroids-2026a.json", "exploratory_horizons_coverage.primary")
    add(f"Team statement for the batch: pending = {str(batch['team_statement_pending']).lower()}.", "batches/asteroids-2026a.json",
        "team_statement_pending")

    lines += ["", "## How much SPHEREx data the site uses", ""]
    index = load("index.json")
    observations = set()
    for target in index["targets"]:
        path = DATA / target["key"] / "investigation.json"
        if path.exists():
            for observation in json.loads(path.read_text())["observations"]:
                if observation.get("collection", "").startswith("spherex"):
                    observations.add(observation["obs_key"])
    add(f"{len(observations):,} SPHEREx exposures (exposure × detector) in the {len(index['targets'])} target investigations.",
        "<key>/investigation.json", "observations[].obs_key (collection spherex_*)")
    asteroid_exposures = set()
    for row in batch["rows"]:
        training = load(f"trials/{row['trial_id']}/training.json")
        asteroid_exposures.update(p["obs_keys"][0] for p in training["points"])
        asteroid_exposures.update(r["obs_key"] for r in training["rejected"])
        verification = load(f"trials/{row['trial_id']}/verification.json")
        asteroid_exposures.update(c["obs_key"] for c in verification.get("candidates", []))
        asteroid_exposures.update(f"{c['static_reference']['obs_id']}_ref" for c in verification.get("candidates", [])
                                  if c.get("static_reference"))
    add(f"{len(asteroid_exposures):,} more SPHEREx exposures opened for the asteroid batch (training, evaluation and static "
        "references).", "trials/asteroid-*/training.json, verification.json",
        "points[].obs_keys, rejected[].obs_key, candidates[].obs_key, candidates[].static_reference.obs_id")
    add(f"{exposures} exposures (already in the investigations) reused with their PSF for the Planet X depth.", "planetx/depth.json",
        "bands[].fields[].exposures[].obs_key")
    add(f"Fields: {len(index['targets'])} targets on the site ({', '.join(t['key'] for t in index['targets'])}), plus 8 asteroids.",
        "index.json", "targets[].key")
    add(f"Data releases: {', '.join(index['releases'])}.", "index.json", "releases")
    return "\n".join(lines) + "\n"


if __name__ == "__main__":
    OUT.write_text(build())
    print(OUT)
