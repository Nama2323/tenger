const DEFAULT_LANGUAGE = 'en';
let language = DEFAULT_LANGUAGE;

export function currentLanguage() {
  return language;
}

/** Kept for a later translation; the interface offers English only, so this is not called from the UI. */
export function setLanguage(next) {
  if (!TEXT[next]) return;
  language = next;
  if (typeof document !== 'undefined') document.documentElement.lang = next;
}

/** Whether a key has text (in the current language or the English fallback). */
export function has(key) {
  return key in TEXT[language] || key in TEXT.en;
}

/** Text for a key with {name} placeholders filled; the key itself if it is missing (tests catch those). */
export function t(key, values = {}) {
  const template = TEXT[language][key] ?? TEXT.en[key] ?? key;
  return template.replace(/\{(\w+)\}/g, (_, name) => (values[name] ?? ''));
}

/** Text for a key that comes from data: a generic fallback mentioning the key when there is no text yet. */
export function tData(key, fallbackKey, values = {}) {
  return has(key) ? t(key, values) : t(fallbackKey, { key, ...values });
}

/** Adds text for data keys that are still missing (from strings.en.json at run time); never replaces any. */
export function addMissingStrings(strings) {
  let added = 0;
  for (const [key, text] of Object.entries(strings ?? {})) {
    if (typeof text === 'string' && !(key in TEXT.en)) {
      TEXT.en[key] = text;
      added += 1;
    }
  }
  return added;
}

export function applyTranslations(root = document) {
  for (const node of root.querySelectorAll('[data-t]')) node.textContent = t(node.dataset.t);
  for (const node of root.querySelectorAll('[data-t-placeholder]')) node.placeholder = t(node.dataset.tPlaceholder);
  for (const node of root.querySelectorAll('[data-t-label]')) node.setAttribute('aria-label', t(node.dataset.tLabel));
}

